// Builds the towns files from the town-map filenames in the dnd5e folder (DND5E_DIR, default
// ~/dnd5e). Only filenames are read, never images. Run: pnpm tsx scripts/port/port-town-maps.ts
// Original and generic names go in data/original/towns.json (committed); names from published
// settings or the real world (PUBLISHED_TOWNS) go in data/imported-private/towns.json (gitignored).
// It prints the banner paths missing from the asset manifests: add original ones to
// assets.manifest.txt and private ones to the gitignored assets.manifest.private.txt, then run
// pnpm sync-assets.
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'node:path'
import type { Town } from '../../src/schema/world'
import { MANIFEST, PRIVATE_MANIFEST, readManifests } from '../sync-assets'
import { collectTowns, splitTowns } from './town-maps'

/** Towns the user has labelled on the Altaeus map keep their marker. */
const PINNED: Record<string, string> = {
  amiton: 'deaddar-marsh-1', // AMITON text layer at (705, 989) in _altaeus with town names.xcf
}

const root = join(process.env.DND5E_DIR ?? join(homedir(), 'dnd5e'), 'town maps')
const files = (dir: string) =>
  readdirSync(join(root, dir), { withFileTypes: true })
    .filter((e) => e.isFile())
    .map((e) => e.name)

const towns = collectTowns([
  { folder: 'town maps/__altaeus', altaeus: true, files: files('__altaeus') },
  { folder: 'town maps', altaeus: false, files: files('.') },
]).map((town) => (Object.hasOwn(PINNED, town.id) ? { ...town, site: PINNED[town.id] } : town))
const { original, imported } = splitTowns(towns)

const NOTES =
  "Generated by scripts/port/port-town-maps.ts from the user's town-map filenames (Name - description - alignment) in ~/dnd5e/town maps/ and its __altaeus/ folder. Hints come from the description words; edit the script's word lists rather than this file."
const write = (path: string, source: string, notes: string, entries: Town[]) =>
  writeFileSync(
    path,
    JSON.stringify(
      { $schema: '../_schema/towns.schema.json', kind: 'towns', source, notes, entries },
      null,
      2
    ) + '\n'
  )
write(
  'data/original/towns.json',
  'original',
  `${NOTES} Names from published settings or the real world are in data/imported-private/towns.json instead.`,
  original
)
mkdirSync('data/imported-private', { recursive: true })
write(
  'data/imported-private/towns.json',
  'imported-private',
  `${NOTES} These names come from published settings or the real world (PUBLISHED_TOWNS in scripts/port/town-maps.ts), so they are kept out of git.`,
  imported
)

const manifest = new Set(readManifests('.'))
const missing = (list: Town[]) =>
  list
    .map((t) => t.banner)
    .filter((b): b is string => !!b && !b.startsWith('town maps/__altaeus/') && !manifest.has(b))
console.log(`wrote ${original.length} original and ${imported.length} private towns`)
for (const [file, list] of [
  [MANIFEST, original],
  [PRIVATE_MANIFEST, imported],
] as const) {
  const absent = missing(list)
  if (absent.length > 0) console.log(`banners missing from ${file}:\n${absent.join('\n')}`)
}
